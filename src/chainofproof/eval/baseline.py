"""EVALUATION ONLY: the Hayabusa-only baseline (no tuning, rule titles and levels only).

For each answer-key action and each adjudicated ``true_finding``: does any Hayabusa detection link
to a real supporting event? This is the reference point for the Phase 9 evaluation.
"""

from __future__ import annotations

from contextlib import closing
from dataclasses import dataclass, field
from pathlib import Path

from chainofproof.config import Paths
from chainofproof.custody.db import connect
from chainofproof.eval.gt_link import EvalIndex
from chainofproof.schemas.adjudication import Adjudication, Verdict
from chainofproof.schemas.scenario import AnswerKey, Scenario, SourceKind
from chainofproof.tools.norm_store import LATEST_RUNS

LEVELS = ["critical", "high", "medium", "low", "informational"]


@dataclass
class BaselineRow:
    """One key item and the rules that fired on its real supporting events."""

    item_id: str
    kind: str  # GT-ACT or GT-ADJ
    has_real_ref: bool
    rules: list[tuple[str, str]] = field(default_factory=list)  # (title, level), sorted, unique

    @property
    def detected(self) -> bool:
        """True when at least one rule fired."""
        return bool(self.rules)

    @property
    def best_level(self) -> str | None:
        """Highest level among the rules that fired."""
        lv = {lvl for _, lvl in self.rules}
        return next((x for x in LEVELS if x in lv), None) if lv else None


def _detections(paths: Paths, case_id: str) -> dict[str, set[tuple[str, str]]]:
    sql = (
        "SELECT event_uid, rule_title, level FROM detections WHERE event_uid IS NOT NULL "
        f"AND norm_run_id IN ({LATEST_RUNS})"
    )
    out: dict[str, set[tuple[str, str]]] = {}
    with closing(connect(paths.db_path)) as conn:
        for r in conn.execute(sql, [case_id]):
            out.setdefault(r["event_uid"], set()).add((r["rule_title"], r["level"]))
    return out


def compute_baseline(
    paths: Paths, case_id: str, idx: EvalIndex, key: AnswerKey, adj: Adjudication, scn: Scenario
) -> list[BaselineRow]:
    """Baseline rows for every GT-ACT and every true_finding adjudication entry."""
    real = {s.source_key for s in scn.sources if s.kind == SourceKind.real_evtx}
    dets = _detections(paths, case_id)
    rows = []
    for a in key.actions:
        refs = [r for r in a.supporting_refs if r.source_key in real]
        rows.append(
            _row(a.id, "GT-ACT", [(r.source_key, r.event_record_id) for r in refs], idx, dets)
        )
    for e in adj.entries:
        if e.verdict == Verdict.true_finding:
            rows.append(_row(e.id, "GT-ADJ", [(e.source_key, e.event_record_id)], idx, dets))
    return rows


def _row(item_id: str, kind: str, refs: list[tuple[str, int]], idx: EvalIndex, dets) -> BaselineRow:
    found: set[tuple[str, str]] = set()
    for sk, rid in refs:
        for uid in idx.uids(sk, rid):
            found |= dets.get(uid, set())
    order = {lvl: i for i, lvl in enumerate(LEVELS)}
    return BaselineRow(
        item_id, kind, bool(refs), sorted(found, key=lambda t: (order.get(t[1], 9), t[0]))
    )


def totals_by_level(rows: list[BaselineRow], kind: str) -> dict[str, int]:
    """Number of items of ``kind`` per best detection level, plus ``none``."""
    out = dict.fromkeys([*LEVELS, "none"], 0)
    for r in rows:
        if r.kind == kind:
            out[r.best_level or "none"] += 1
    return out


def render_markdown(case_rows: dict[str, list[BaselineRow]]) -> str:
    """docs/hayabusa_baseline.md text (titles and levels only)."""
    lines = [
        "# Hayabusa-only baseline", "",
        "Generated by `eval-coverage`. Rule titles and levels only; no tuning was applied. An item",
        "counts as *detected* when at least one Hayabusa rule fired on one of its REAL supporting",
        "events (synthetic companion lines are invisible to Hayabusa). This is the reference point",
        "for the Phase 9 evaluation.", "",
    ]  # fmt: skip
    for case, rows in case_rows.items():
        lines += [f"## {case}", "", "| item | real ref | detected | best level | rules (level) |",
                  "|---|---|---|---|---|"]  # fmt: skip
        for r in rows:
            rules = "; ".join(f"{t} ({lv})" for t, lv in r.rules) or "-"
            ref, hit = ("yes" if r.has_real_ref else "no"), ("yes" if r.detected else "no")
            lines.append(f"| {r.item_id} | {ref} | {hit} | {r.best_level or '-'} | {rules} |")
        for kind in ("GT-ACT", "GT-ADJ"):
            sub = [r for r in rows if r.kind == kind]
            hit = sum(r.detected for r in sub)
            by = ", ".join(f"{k}={v}" for k, v in totals_by_level(rows, kind).items() if v)
            lines += ["", f"**{kind}: {hit} of {len(sub)} detected** (best level: {by})"]
        lines.append("")
    return "\n".join(lines) + "\n"


def write_markdown(path: Path, case_rows: dict[str, list[BaselineRow]]) -> None:
    """Write the baseline document (overwrites the generated file only)."""
    Path(path).write_text(render_markdown(case_rows), encoding="utf-8", newline="\n")
