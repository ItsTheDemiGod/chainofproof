def test_same_seed_byte_identical(fx, tmp_path, monkeypatch):
    scn, inv = fx

    def forbidden(*a, **k):
        raise AssertionError("wall clock / system randomness used")

    monkeypatch.setattr(time, "time", forbidden)
    monkeypatch.setattr(time, "time_ns", forbidden)
    monkeypatch.setattr(uuid, "uuid4", forbidden)
    a = generate_variant(scn, inv, Variant.perturbed, tmp_path / "a")
    b = generate_variant(scn, inv, Variant.perturbed, tmp_path / "b")
    assert a.hashes == b.hashes and len(a.hashes) == 6
    for rel in a.hashes:
        assert (tmp_path / "a" / rel).read_bytes() == (tmp_path / "b" / rel).read_bytes()


def test_different_seed_differs(fx, tmp_path):
    scn, inv = fx
    other = scn.model_copy(update={"seed": scn.seed + 1})
    a = generate_variant(scn, inv, Variant.clean, tmp_path / "a")
    b = generate_variant(other, inv, Variant.clean, tmp_path / "b")
    assert all(a.hashes[r] != b.hashes[r] for r in a.hashes)


