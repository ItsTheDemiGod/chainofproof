GOOD = "# SYNTHETIC x\n\nseq=000001 ts=2024-03-12T09:00:00Z host=H event=E user=u\n  \n"


def test_auth_parser_skips_comments_and_blanks():
    rows = parse_auth_text(GOOD)
    assert rows == [
        {"seq": "000001", "ts": "2024-03-12T09:00:00Z", "host": "H", "event": "E", "user": "u"}
    ]


@pytest.mark.parametrize(
    "line",
    [
        "seq=1 ts=2024-03-12T09:00:00Z host=H",  # missing event
        "seq=1 ts=2024-03-12T09:00:00 host=H event=E",  # bad timestamp
        "seq=x ts=2024-03-12T09:00:00Z host=H event=E",  # bad seq
        "seq=1 ts=2024-03-12T09:00:00Z host=H event=E garbage",  # not key=value
        "seq=1 seq=2 ts=2024-03-12T09:00:00Z host=H event=E",  # duplicate key
    ],
)
def test_auth_parser_rejects_malformed(line):
    with pytest.raises(CompanionParseError, match="line 1"):
        parse_auth_text(line)


def test_fs_parser():
    head = (
        "record_id,host,path,size,si_created,si_modified,si_accessed,si_changed,"
        "fn_created,fn_modified,fn_accessed,fn_changed,note"
    )
    ts = ",".join(["2024-03-12T09:00:00Z"] * 8)
    assert len(parse_fs_text(f"# c\n{head}\n\n1,H,C:\\a,5,{ts},\n")) == 1
    with pytest.raises(CompanionParseError, match="header"):
        parse_fs_text("a,b\n1,2\n")
    with pytest.raises(CompanionParseError, match="row 2"):
        parse_fs_text(f"{head}\n1,H,C:\\a,5\n")
    with pytest.raises(CompanionParseError, match="timestamp"):
        parse_fs_text(f"{head}\n1,H,C:\\a,5,bad,{','.join(['2024-03-12T09:00:00Z'] * 7)},\n")
