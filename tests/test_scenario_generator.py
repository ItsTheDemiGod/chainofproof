def _artifact_rows(d, res):
    rows = {r["record_id"]: r for r in parse_fs_csv(d / "fs_srv_file_02.csv")}
    return [
        rows[str(i)]
        for t, (_, i) in res.fs_ids.items()
        if t in ("renamed_svchost", "psexec_client")
    ]


def test_p1_timestomp_measured(gens):
    dc, rc = gens[Variant.clean]
    dp, rp = gens[Variant.perturbed]
    for r in _artifact_rows(dc, rc):
        assert r["si_created"] == r["fn_created"] and r["si_modified"] == r["fn_modified"]
    stomped = [
        r
        for r in parse_fs_csv(dp / "fs_srv_file_02.csv")
        if parse_ts(r["fn_created"]) - parse_ts(r["si_created"]) > timedelta(days=365)
    ]
    assert len(stomped) == 2
    assert all(
        r["fn_created"] == r2["fn_created"]
        for r, r2 in zip(stomped, _artifact_rows(dc, rc), strict=True)
    )
    # benign rows stay consistent (within a few seconds) in BOTH variants
    for d in (dc, dp):
        for r in parse_fs_csv(d / "fs_dc_01.csv"):
            assert (
                abs((parse_ts(r["si_modified"]) - parse_ts(r["fn_modified"])).total_seconds()) <= 3
            )


def test_p2_skew_measured(gens):
    clean = parse_auth_log(gens[Variant.clean][0] / "auth_srv_file_02.log")
    pert = parse_auth_log(gens[Variant.perturbed][0] / "auth_srv_file_02.log")
    assert [r["seq"] for r in clean] == [r["seq"] for r in pert]
    for c, p in zip(clean, pert, strict=True):
        assert (parse_ts(p["ts"]) - parse_ts(c["ts"])).total_seconds() == 420
    # other hosts are untouched
    for h in ("ws_fin_07",):
        assert (gens[Variant.clean][0] / f"auth_{h}.log").read_bytes() == (
            gens[Variant.perturbed][0] / f"auth_{h}.log"
        ).read_bytes()


def test_p2_paired_lines_match_real_event_times(fx, gens):
    scn, inv = fx
    ctx = GenContext(scn, inv)
    want = {
        e.facts["PipeName"].lstrip("\\"): ctx.virt("s4", e.real_time)
        for e in inv.keys_for("S4").result.events
        if e.event_id == 18
    }

    def paired(v):
        rows = parse_auth_log(gens[v][0] / "auth_srv_file_02.log")
        return {r["pipe"]: parse_ts(r["ts"]) for r in rows if r["event"] == "NAMED_PIPE_OPEN"}

    assert set(paired(Variant.clean)) == set(want) and len(want) == 3
    for pipe, t in want.items():
        assert paired(Variant.clean)[pipe] == t
        assert (paired(Variant.perturbed)[pipe] - t).total_seconds() == 420


def test_p3_gap_measured(gens):
    clean = parse_auth_log(gens[Variant.clean][0] / "auth_dc_01.log")
    pert = parse_auth_log(gens[Variant.perturbed][0] / "auth_dc_01.log")
    assert [int(r["seq"]) for r in clean] == list(range(1, len(clean) + 1))
    seqs = [int(r["seq"]) for r in pert]
    jumps = [(a, b) for a, b in zip(seqs, seqs[1:], strict=False) if b != a + 1]
    assert len(jumps) == 1
    a, b = jumps[0]
    removed = [r for r in clean if a < int(r["seq"]) < b]
    assert len(removed) == len(clean) - len(pert) >= 1
    lo, hi = parse_ts(removed[0]["ts"]), parse_ts(removed[-1]["ts"])
    assert any(r["event"] == "DIRECTORY_REPLICATION_REQUEST" for r in removed)
    assert not any(lo <= parse_ts(r["ts"]) <= hi for r in pert)


def test_key_agrees_with_measured_data(fx, gens, tmp_path, monkeypatch):
    scn, inv = fx
    monkeypatch.setenv("CHAINOFPROOF_SCENARIOS_DIR", str(tmp_path / "scenarios"))
    build.write_keys(SID)
    key = load_key(tmp_path / "scenarios" / SID / "key_perturbed.yaml", scn)
    dp, _ = gens[Variant.perturbed]
    by_kind = {c.kind.value: c for c in key.contradictions}
    # P1: exactly the recorded files are stomped, with the recorded delta
    p1 = by_kind["timestomp"]
    rows = {r["record_id"]: r for r in parse_fs_csv(dp / "fs_srv_file_02.csv")}
    assert p1.magnitude == len(p1.params["files"]) == 2
    for f in p1.params["files"]:
        r = rows[str(f["record_id"])]
        assert r["path"] == f["path"] and r["si_created"] == f["si_created"]
        assert (parse_ts(r["fn_created"]) - parse_ts(r["si_created"])).total_seconds() == f[
            "delta_seconds"
        ]
    # P2
    p2 = by_kind["clock_skew"]
    lines = parse_auth_log(dp / "auth_srv_file_02.log")
    clean = parse_auth_log(gens[Variant.clean][0] / "auth_srv_file_02.log")
    assert p2.params["lines_shifted"] == len(lines)
    assert {
        (parse_ts(a["ts"]) - parse_ts(b["ts"])).total_seconds()
        for a, b in zip(lines, clean, strict=True)
    } == {p2.magnitude}
    # P3
    p3 = by_kind["log_gap"].params
    dc = parse_auth_log(dp / "auth_dc_01.log")
    seqs = [int(r["seq"]) for r in dc]
    assert p3["first_removed_seq"] - 1 in seqs and p3["last_removed_seq"] + 1 in seqs
    assert not set(range(p3["first_removed_seq"], p3["last_removed_seq"] + 1)) & set(seqs)
    assert p3["removed_lines"] == p3["last_removed_seq"] - p3["first_removed_seq"] + 1
    lo, hi = parse_ts(p3["window_start"]), parse_ts(p3["window_end"])
    assert (hi - lo).total_seconds() == by_kind["log_gap"].magnitude
    assert not [r for r in dc if lo <= parse_ts(r["ts"]) < hi]
    # supporting refs of the synthetic lines point at lines that exist (removed line absent)
    present = {("auth_dc_01", s) for s in seqs}
    for a in key.actions:
        for r in a.supporting_refs:
            if r.source_key == "auth_dc_01":
                assert (r.source_key, r.event_record_id) in present


